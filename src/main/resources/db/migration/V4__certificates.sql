CREATE TABLE certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    certificate_number VARCHAR(40) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    category_id BIGINT NOT NULL REFERENCES categories(id),
    holder_name VARCHAR(250) NOT NULL,
    direction_name VARCHAR(160) NOT NULL,
    attempt_id BIGINT NOT NULL UNIQUE REFERENCES test_attempts(id),
    correct_answers INTEGER NOT NULL,
    total_questions INTEGER NOT NULL,
    score NUMERIC(7, 2) NOT NULL,
    issued_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX ix_certificates_user_issued ON certificates(user_id, issued_at);
