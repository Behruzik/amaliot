CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone VARCHAR(32) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    token_version BIGINT NOT NULL DEFAULT 0,
    first_name VARCHAR(100),
    last_name VARCHAR(100),
    role VARCHAR(16) NOT NULL,
    gender VARCHAR(16),
    offer_accepted BOOLEAN NOT NULL,
    birth_date DATE,
    region VARCHAR(120),
    district VARCHAR(120),
    address VARCHAR(500),
    avatar_url VARCHAR(500),
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_app_users_role ON app_users(role);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL UNIQUE,
    description VARCHAR(2000),
    image_url VARCHAR(500),
    active BOOLEAN NOT NULL,
    duration_minutes INTEGER NOT NULL,
    question_count INTEGER NOT NULL,
    additional_question_count INTEGER NOT NULL,
    retake_delay_hours INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_categories_active ON categories(active);

CREATE TABLE questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories(id),
    body VARCHAR(5000) NOT NULL,
    image_url VARCHAR(500),
    difficulty VARCHAR(16) NOT NULL,
    answer_type VARCHAR(16) NOT NULL,
    numeric_answer DECIMAL(20,6),
    numeric_tolerance DECIMAL(20,6),
    active BOOLEAN NOT NULL,
    author_id BIGINT REFERENCES app_users(id),
    editor_id BIGINT REFERENCES app_users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_questions_category_active ON questions(category_id, active);
CREATE INDEX ix_questions_type ON questions(answer_type);

CREATE TABLE answer_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    label VARCHAR(2000),
    image_url VARCHAR(500),
    is_correct BOOLEAN NOT NULL
);
CREATE INDEX ix_options_question ON answer_options(question_id);

CREATE TABLE test_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    category_id BIGINT NOT NULL REFERENCES categories(id),
    status VARCHAR(16) NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deadline_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    total_questions INTEGER NOT NULL,
    correct_answers INTEGER NOT NULL,
    score DECIMAL(7,2) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_attempt_user_category ON test_attempts(user_id, category_id, created_at);
CREATE INDEX ix_attempt_status_created ON test_attempts(status, created_at);

CREATE TABLE attempt_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id BIGINT NOT NULL REFERENCES test_attempts(id) ON DELETE CASCADE,
    source_question_id BIGINT REFERENCES questions(id),
    source_category_id BIGINT NOT NULL REFERENCES categories(id),
    body VARCHAR(5000) NOT NULL,
    image_url VARCHAR(500),
    answer_type VARCHAR(16) NOT NULL,
    numeric_answer DECIMAL(20,6),
    numeric_tolerance DECIMAL(20,6),
    display_order INTEGER NOT NULL
);
CREATE INDEX ix_attempt_questions_attempt ON attempt_questions(attempt_id, display_order);

CREATE TABLE attempt_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_question_id BIGINT NOT NULL REFERENCES attempt_questions(id) ON DELETE CASCADE,
    label VARCHAR(2000),
    image_url VARCHAR(500),
    is_correct BOOLEAN NOT NULL
);
CREATE INDEX ix_attempt_options_question ON attempt_options(attempt_question_id);

CREATE TABLE attempt_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_question_id BIGINT NOT NULL UNIQUE REFERENCES attempt_questions(id) ON DELETE CASCADE,
    numeric_value DECIMAL(20,6),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE attempt_answer_options (
    answer_id BIGINT NOT NULL REFERENCES attempt_answers(id) ON DELETE CASCADE,
    option_id BIGINT NOT NULL REFERENCES attempt_options(id),
    PRIMARY KEY (answer_id, option_id)
);

CREATE TABLE retake_grants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    category_id BIGINT NOT NULL REFERENCES categories(id),
    granted_by_id BIGINT NOT NULL REFERENCES app_users(id),
    consumed BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_retake_grant_lookup ON retake_grants(user_id, category_id, consumed);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT NOT NULL,
    action VARCHAR(80) NOT NULL,
    target_type VARCHAR(60) NOT NULL,
    target_id BIGINT NOT NULL,
    details VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_audit_target ON audit_logs(target_type, target_id, created_at);

CREATE TABLE revoked_tokens (
    token_id VARCHAR(64) PRIMARY KEY,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_revoked_tokens_expiry ON revoked_tokens(expires_at);
