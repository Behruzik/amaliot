ALTER TABLE test_attempts ADD COLUMN archived_at TIMESTAMP WITH TIME ZONE;
CREATE INDEX ix_attempt_archived_created ON test_attempts(archived_at, created_at);

CREATE TABLE geo_regions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_geo_regions_name UNIQUE (name)
);

CREATE TABLE geo_districts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_id BIGINT NOT NULL REFERENCES geo_regions(id),
    name VARCHAR(120) NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_geo_districts_region_name UNIQUE (region_id, name)
);
CREATE INDEX ix_geo_districts_region_active ON geo_districts(region_id, active);

CREATE TABLE managed_content (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_type VARCHAR(24) NOT NULL,
    content VARCHAR(20000) NOT NULL,
    updated_by_id BIGINT REFERENCES app_users(id),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_managed_content_type UNIQUE (content_type)
);
